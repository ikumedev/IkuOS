function strtimer(){

  if(!ontime){

    srttime = Date.now() - passedtime;
    timer = setInterval(update, 10);
    ontime = true

  }

}

function stptimer(){

  if(ontime){
    clearInterval(timer);
    passedtime = Date.now() - srttime;
    ontime = false
  }

}

function rsttimer(){
   
  clearInterval(timer);
   srttime = 0;
   passedtime = 0;
   ontime = false;

   display.textContent = "00:00:00:00"


}

function update(){

  const currenttime = Date.now();
  passedtime = currenttime - srttime;

  let hours = Math.floor( passedtime / (1000 * 60 * 60 ));
  let min = Math.floor( passedtime / ( 1000 * 60  ) % 60 );
  let sec = Math.floor( passedtime / 1000 % 60);
  let mill = Math.floor(passedtime % 1000/ 10)

  hours = String(hours).padStart(2, "0")
  min = String(min).padStart(2, "0")
  sec = String(sec).padStart(2, "0")
  mill = String(mill).padStart(2, "0")

  display.textContent = `${hours}:${min}:${sec}:${mill}`;
}


